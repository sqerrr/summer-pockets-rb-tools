#!/usr/bin/env python3
"""Транскрипция японских имён из ромадзи в русский по решению DEC-0035.

Ромадзи берётся из английского слота игры: он даёт надёжное ЧТЕНИЕ каждого
иероглифического имени. Само английское написание при этом образцом не является -
это Хэпбёрн под английскую фонетику, - поэтому кириллица выводится нашим
правилом, а не побуквенным переносом.

Правило: система Поливанова. し -> си, ち -> ти, じ -> дзи, ず -> дзу,
しゃ/しゅ/しょ -> ся/сю/сё, え -> э, долгота не отражается. Формы, уже
закреплённые в docs/glossary.yaml, имеют приоритет над таблицей.
"""
from __future__ import annotations

import re

# Порядок важен: длинные сочетания разбираются раньше коротких.
TABLE: list[tuple[str, str]] = [
    # Палатализованные.
    ("kya", "кя"), ("kyu", "кю"), ("kyo", "кё"),
    ("gya", "гя"), ("gyu", "гю"), ("gyo", "гё"),
    ("sha", "ся"), ("shu", "сю"), ("sho", "сё"),
    ("ja", "дзя"), ("ju", "дзю"), ("jo", "дзё"),
    ("cha", "тя"), ("chu", "тю"), ("cho", "тё"),
    ("nya", "ня"), ("nyu", "ню"), ("nyo", "нё"),
    ("hya", "хя"), ("hyu", "хю"), ("hyo", "хё"),
    ("bya", "бя"), ("byu", "бю"), ("byo", "бё"),
    ("pya", "пя"), ("pyu", "пю"), ("pyo", "пё"),
    ("mya", "мя"), ("myu", "мю"), ("myo", "мё"),
    ("rya", "ря"), ("ryu", "рю"), ("ryo", "рё"),
    # Трёхбуквенные слоги.
    ("shi", "си"), ("chi", "ти"), ("tsu", "цу"),
    # Двухбуквенные.
    ("ka", "ка"), ("ki", "ки"), ("ku", "ку"), ("ke", "кэ"), ("ko", "ко"),
    ("ga", "га"), ("gi", "ги"), ("gu", "гу"), ("ge", "гэ"), ("go", "го"),
    ("sa", "са"), ("su", "су"), ("se", "сэ"), ("so", "со"),
    ("za", "дза"), ("ji", "дзи"), ("zu", "дзу"), ("ze", "дзэ"), ("zo", "дзо"),
    ("ta", "та"), ("te", "тэ"), ("to", "то"),
    ("da", "да"), ("de", "дэ"), ("do", "до"),
    ("na", "на"), ("ni", "ни"), ("nu", "ну"), ("ne", "нэ"), ("no", "но"),
    ("ha", "ха"), ("hi", "хи"), ("fu", "фу"), ("he", "хэ"), ("ho", "хо"),
    ("ba", "ба"), ("bi", "би"), ("bu", "бу"), ("be", "бэ"), ("bo", "бо"),
    ("pa", "па"), ("pi", "пи"), ("pu", "пу"), ("pe", "пэ"), ("po", "по"),
    ("ma", "ма"), ("mi", "ми"), ("mu", "му"), ("me", "мэ"), ("mo", "мо"),
    ("ya", "я"), ("yu", "ю"), ("yo", "ё"),
    ("ra", "ра"), ("ri", "ри"), ("ru", "ру"), ("re", "рэ"), ("ro", "ро"),
    ("wa", "ва"), ("wo", "о"),
    # Одиночные.
    ("a", "а"), ("i", "и"), ("u", "у"), ("e", "э"), ("o", "о"),
    ("n", "н"),
]

# Долгота в английском слоте уже снята, но на случай макронов и удвоений.
LONG = [("ō", "o"), ("ū", "u"), ("ā", "a"), ("ē", "e"), ("ī", "i"),
        ("ou", "o"), ("oo", "o"), ("uu", "u")]

DOUBLE_CONSONANT = re.compile(r"([kstpgzdbcm])\1")


def translit(romaji: str) -> str:
    """Ромадзи -> кириллица. Регистр первой буквы сохраняется."""
    if not romaji:
        return ""
    text = romaji.strip()
    upper = text[:1].isupper()
    text = text.lower()

    for src, dst in LONG:
        text = text.replace(src, dst)
    # Удвоенная согласная перед слогом: っ.
    text = DOUBLE_CONSONANT.sub(lambda m: m.group(1) * 2, text)

    out: list[str] = []
    i = 0
    while i < len(text):
        for src, dst in TABLE:
            if text.startswith(src, i):
                out.append(dst)
                i += len(src)
                break
        else:
            # Неразобранный символ переносим как есть: молчаливая потеря хуже.
            out.append(text[i])
            i += 1

    result = "".join(out)
    return result[:1].upper() + result[1:] if upper else result


LATIN = re.compile(r"[a-zA-Z]")


def looks_like_romaji(text: str) -> bool:
    """Разбирается ли строка нашей таблицей без остатка.

    Английское слово вместо ромадзи даёт смесь кириллицы с латиницей - «Биrd»
    вместо отказа. Молчаливая порча хуже пустого результата, поэтому вход
    проверяется до, а не после.
    """
    if not text.strip():
        return False
    return not LATIN.search(translit(text))
